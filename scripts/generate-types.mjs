/** Generate the Studio manifest wire types from the Rust-exported JSON Schema. */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const schemaPath = new URL('../docs/video.schema.json', import.meta.url);
const outputPath = new URL('../studio/src/generated.ts', import.meta.url);
const schemaText = await readFile(schemaPath, 'utf8');
const schema = JSON.parse(schemaText.replace(/^\uFEFF/, ''));
const definitions = schema.$defs || {};
const isIdentifier = value => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value);
const propertyName = value => isIdentifier(value) ? value : JSON.stringify(value);

function typeOf(definition, indent = '') {
  if (definition === true || definition === undefined) return 'JsonValue';
  if (definition === false) return 'never';
  if (definition.$ref) {
    const name = definition.$ref.replace(/^#\/\$defs\//, '');
    if (name === definition.$ref || !Object.hasOwn(definitions, name) || !isIdentifier(name)) {
      throw new Error(`Unsupported schema reference: ${definition.$ref}`);
    }
    return name;
  }
  if (Object.hasOwn(definition, 'const')) return JSON.stringify(definition.const);
  if (definition.enum) return definition.enum.map(value => JSON.stringify(value)).join(' | ');
  if (definition.anyOf || definition.oneOf) {
    return (definition.anyOf || definition.oneOf).map(value => `(${typeOf(value, indent)})`).join(' | ');
  }
  if (definition.allOf) return definition.allOf.map(value => `(${typeOf(value, indent)})`).join(' & ');
  if (Array.isArray(definition.type)) {
    return definition.type.map(type => typeOf({ ...definition, type }, indent)).join(' | ');
  }
  switch (definition.type) {
    case 'integer':
    case 'number':
      return definition.minimum !== undefined && definition.minimum === definition.maximum
        ? JSON.stringify(definition.minimum) : 'number';
    case 'string': return 'string';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `Array<${typeOf(definition.items, indent)}>`;
    case 'object': {
      const properties = Object.entries(definition.properties || {}).sort(([left], [right]) => left.localeCompare(right, 'en'));
      if (!properties.length) return definition.additionalProperties === false
        ? 'Record<string, never>' : `Record<string, ${typeOf(definition.additionalProperties, indent)}>`;
      const required = new Set(definition.required || []);
      const fields = properties.map(([name, value]) => `${indent}  ${propertyName(name)}${required.has(name) ? '' : '?'}: ${typeOf(value, `${indent}  `)};`);
      if (definition.additionalProperties && definition.additionalProperties !== false) {
        fields.push(`${indent}  [key: string]: ${typeOf(definition.additionalProperties, indent)};`);
      }
      return `{\n${fields.join('\n')}\n${indent}}`;
    }
    case undefined: return 'JsonValue';
    default: throw new Error(`Unsupported schema type: ${definition.type}`);
  }
}

const digest = createHash('sha256').update(JSON.stringify(schema)).digest('hex');
const declarations = [
  '// Generated by scripts/generate-types.mjs. Edit src/model.rs and regenerate the schema instead.',
  `// Schema SHA-256: ${digest}`,
  'export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };',
  ...Object.entries(definitions).sort(([left], [right]) => left.localeCompare(right, 'en')).map(([name, value]) => {
    if (!isIdentifier(name)) throw new Error(`Invalid schema definition name: ${name}`);
    return `export type ${name} = ${typeOf(value)};`;
  }),
  `export type Manifest = ${typeOf(schema)};`,
];
const generated = `${declarations.join('\n\n')}\n`;

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current.replace(/\r\n/g, '\n') !== generated) {
    throw new Error('Studio manifest types are stale. Run node scripts/generate-types.mjs from the repository root.');
  }
  console.log('Studio manifest types match docs/video.schema.json.');
} else {
  await writeFile(outputPath, generated, 'utf8');
  console.log(`Generated ${fileURLToPath(outputPath)}.`);
}
